static const char *const NB_RING[] = {
    "# Ring buffer notes\n\n",
    "A single-producer, single-consumer queue needs no lock, only two indices and the ",
    "right memory order. Written down because I re-derive this every year. #dev/c\n\n",
    "```c\n",
    "typedef struct {\n",
    "    uint32_t head;          /* written by the producer */\n",
    "    uint32_t tail;          /* written by the consumer */\n",
    "    float samples[1024];    /* a power of two: a mask wraps */\n",
    "} Ring;\n",
    "\n",
    "static bool ring_push(Ring *r, float value)\n",
    "{\n",
    "    uint32_t head = atomic_load(&r->head);\n",
    "    if (head - atomic_load(&r->tail) == 1024)\n",
    "        return false;   // full: drop, never block audio\n",
    "    r->samples[head & 1023] = value;\n",
    "    atomic_store(&r->head, head + 1);\n",
    "    return true;\n",
    "}\n",
    "```\n\n",
    "## Why the indices never wrap\n\n",
    "They run freely and only the array access masks them, so `head - tail` is the fill ",
    "count even across the 32-bit wrap. That is the whole trick, and it is why the ",
    "capacity has to be a power of two.\n\n",
    "> [!danger] Not for two producers\n",
    "> A second producer needs a compare-and-swap on `head`. This version corrupts ",
    "silently under that use.\n",
};

